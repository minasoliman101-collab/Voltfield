/* Builds embed/calculator-widget.js: the script another site includes to put a
   Voltfield calculator on its own page.

     <div class="vf-calc-widget" data-calc="voltage-drop">
       <a href="https://voltfield.org/calculators/voltage-drop.html">Voltage Drop Calculator</a> by Voltfield
     </div>
     <script src="https://voltfield.org/embed/calculator-widget.js" async></script>

   The first version of this widget carried its own copy of the math for three
   calculators, with a note to change both copies together. This one carries no
   math at all. For each calculator it holds the same form markup the page uses
   (scripts/tpl/calc-tools/<slug>.html) and, at run time, puts that markup in an
   iframe built from a string and loads the site's own voltfield-calculators.js
   into it. So the embedded tool IS the tool on the page: every calculator is
   available, and a fix to one is a fix to both.

   An iframe built from a string (srcdoc) rather than one pointing at a page
   here, because the site sends X-Frame-Options: DENY and should keep doing so.
   The frame isolates styles both ways, as the shadow root used to.

   Run after adding a calculator or changing any tool's form markup:
     node scripts/gen-embed-widget.mjs */
import fs from 'node:fs';

const DIR = 'scripts/tpl/calc-tools/';
const tools = {};
for (const f of fs.readdirSync(DIR).filter(x => x.endsWith('.html')).sort()) {
  const slug = f.slice(0, -5);
  const page = `calculators/${slug}.html`;
  if (!fs.existsSync(page)) { console.log('  skipped (no page):', slug); continue; }
  const pageHtml = fs.readFileSync(page, 'utf8');
  const h1 = pageHtml.match(/<h1[^>]*>([\s\S]*?)<\/h1>/);
  if (!h1) throw new Error(slug + ': no h1');
  const title = h1[1].replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&sup2;/g, '²').replace(/&sup3;/g, '³').replace(/&[a-z0-9]+;/g, ' ').replace(/\s+/g, ' ').trim();
  /* From the page, not the template: the page's copy has the metric twins of
     the hint text that add-metric-prose.mjs adds after generation. */
  const sec = pageHtml.match(/<section class="calc-tool"[^>]*>([\s\S]*?)<\/section>/);
  if (!sec) throw new Error(slug + ': no calc-tool section on the page');
  const html = sec[1].replace(/<!--[\s\S]*?-->/g, '').replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim();
  if (!/class="estimator"/.test(html)) throw new Error(slug + ': no estimator in the tool markup');
  tools[slug] = { t: title, h: html };
}
const data = JSON.stringify(tools).split('</script').join('<\\/script');

const out = `/* VOLTFIELD - embeddable calculators. GENERATED by scripts/gen-embed-widget.mjs;
   edit that, not this.

   Usage on any site:
     <div class="vf-calc-widget" data-calc="voltage-drop">
       <a href="https://voltfield.org/calculators/voltage-drop.html">Voltage Drop Calculator</a> by Voltfield
     </div>
     <script src="https://voltfield.org/embed/calculator-widget.js" async></script>

   data-calc    which calculator (${Object.keys(tools).length} available; the list is at voltfield.org/embed-calculators.html)
   data-theme   "light" (default) or "dark"
   data-units   "us" (default) or "metric", on the calculators that have both

   The calculator runs in the reader's browser inside an isolated frame, using
   the same code as the page on voltfield.org. It loads that code and its
   stylesheet from voltfield.org and nothing else: no analytics, no cookies,
   and nothing the reader types is sent anywhere. */
(function(){
  var me=document.currentScript&&document.currentScript.src||'';
  var SITE=/^https?:\\/\\/[^/]+/.test(me)?me.match(/^https?:\\/\\/[^/]+/)[0]:'https://voltfield.org';
  var TOOLS=${data};

  function esc(s){return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/"/g,'&quot;');}

  function render(host){
    if(host.getAttribute('data-vf-ready'))return;
    var slug=host.getAttribute('data-calc')||'', c=TOOLS[slug];
    if(!c)return;                     /* unknown name: leave the fallback link as it is */
    host.setAttribute('data-vf-ready','1');
    var dark=host.getAttribute('data-theme')==='dark';
    var units=host.getAttribute('data-units')==='metric'?'metric':(host.getAttribute('data-units')==='us'?'us':'');
    var page=SITE+'/calculators/'+slug+'.html';

    var doc='<!doctype html><html lang="en" data-theme="'+(dark?'dark':'light')+'"><head><meta charset="utf-8">'+
      '<meta name="viewport" content="width=device-width,initial-scale=1">'+
      '<base href="'+SITE+'/calculators/" target="_blank">'+
      '<link rel="stylesheet" href="'+SITE+'/voltfield-core.css">'+
      '<link rel="stylesheet" href="'+SITE+'/voltfield-calculators.css">'+
      (dark?'<link rel="stylesheet" href="'+SITE+'/voltfield-dark-mode.css">':'')+
      '<style>html,body{margin:0;padding:0;background:transparent!important;min-height:0!important}'+
      'body{padding:1px;font-family:system-ui,-apple-system,"Segoe UI",Roboto,Arial,sans-serif}'+
      '.calc-tool{margin:0;padding:0}.calc-tool .estimator{margin:0 0 1px}</style>'+
      '<script>window.VF_EMBED={page:"'+page+'",base:"'+SITE+'/calculators/"'+(units?',units:"'+units+'"':'')+'};<\\/script>'+
      '</head><body><section class="calc-tool" aria-label="'+esc(c.t)+'">'+c.h+'</section>'+
      '<script src="'+SITE+'/voltfield-calculators.js"><\\/script></body></html>';

    /* The link the snippet came with is plain HTML on the host page, so it is
       there without JavaScript and for anything reading the page's source. It
       is kept, under the calculator. If the snippet had none, one is made. */
    var credit=host.querySelector('a[href*="/calculators/"]');
    var foot=document.createElement('div');
    foot.style.cssText='font:13px/1.5 system-ui,-apple-system,"Segoe UI",Roboto,Arial,sans-serif;margin:6px 2px 0;color:inherit;opacity:.85';
    if(!credit){
      credit=document.createElement('a');
      credit.href=page;credit.textContent=c.t;
    }
    credit.target='_blank';credit.rel='noopener';
    while(host.firstChild)host.removeChild(host.firstChild);
    foot.appendChild(credit);
    foot.appendChild(document.createTextNode(' by Voltfield: method and a worked example'));

    var f=document.createElement('iframe');
    f.title=c.t;
    f.setAttribute('loading','lazy');
    f.style.cssText='display:block;width:100%;border:0;height:420px;background:transparent;color-scheme:'+(dark?'dark':'light');
    f.srcdoc=doc;
    host.appendChild(f);
    host.appendChild(foot);

    /* The frame is as tall as what is in it: results, warnings and the unit
       switch all change that, so it is measured rather than guessed. */
    function fit(){
      try{
        var d=f.contentDocument;if(!d||!d.body)return;
        var h=Math.ceil(d.body.getBoundingClientRect().height)+2;
        if(h>40&&Math.abs(h-parseFloat(f.style.height))>1)f.style.height=h+'px';
      }catch(e){}
    }
    f.addEventListener('load',function(){
      fit();
      try{
        var W=f.contentWindow;
        if(W.ResizeObserver)new W.ResizeObserver(fit).observe(f.contentDocument.body);
        else setInterval(fit,500);
        W.addEventListener('load',fit);
      }catch(e){}
      setTimeout(fit,300);setTimeout(fit,1200);
    });
  }

  function init(){
    var els=document.querySelectorAll('.vf-calc-widget');
    for(var i=0;i<els.length;i++){try{render(els[i]);}catch(e){}}
  }
  window.VoltfieldCalc={render:render,init:init,list:function(){var o=[];for(var k in TOOLS)o.push([k,TOOLS[k].t]);return o;}};
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);
  else init();
})();
`;
fs.writeFileSync('embed/calculator-widget.js', out);
console.log(`embed/calculator-widget.js: ${Object.keys(tools).length} calculators, ${Math.round(out.length / 1024)} KB`);
